		$collection->add_items_at_bottom(
			new Comment_Syntax_Help_Item( 'ba', 'b', 'c' ),
			new Comment_Syntax_Help_Item( 'bc', 'b', 'c' ),
			new Comment_Syntax_Help_Item( 'bb', 'b', 'c' ),
		);
	}

	public function notification_dependency_with( Observer $observer ): Observer_Priority	{
		return Observer_Priority::NONE;
	}
}

/**
 * A class to mock mutator that tests remove_items
 */
class Mock_Mutator_Remove_Items implements Comment_Syntax_Help_Item_Collection_Mutator {
	public function mutate_by_ref( Comment_Syntax_Help_Item_Collection &$collection ): void {
		$collection->add_items_at_bottom(
			new Comment_Syntax_Help_Item( 'ba', 'b', 'c' ),
			new Comment_Syntax_Help_Item( 'bc', 'b', 'c' ),
			new Comment_Syntax_Help_Item( 'bb', 'b', 'c' ),
		);
		$collection->remove_items( 'not here', 'bc', 'bb' );
		$collection->add_items_at_top(
			new Comment_Syntax_Help_Item( 'bb', 'b', 'c' ),
		);
	}

	public function notification_dependency_with( Observer $observer ): Observer_Priority	{
		return Observer_Priority::NONE;
	}
}

/**
 * A class to mock mutator that add items at mixed top and bottom order.
 */
class Mock_Mutator_Add_Mixed implements Comment_Syntax_Help_Item_Collection_Mutator {
	public function mutate_by_ref( Comment_Syntax_Help_Item_Collection &$collection ): void {
		$collection->add_items_at_top(
			new Comment_Syntax_Help_Item( 'a', 'b', 'c' ),
		);
		$collection->add_items_at_bottom(
			new Comment_Syntax_Help_Item( 'aa', 'b', 'c' ),
		);
		$collection->add_items_at_top(
			new Comment_Syntax_Help_Item( 'aaa', 'b', 'c' ),
		);
		$collection->add_items_at_bottom(
			new Comment_Syntax_Help_Item( 'aaaa', 'b', 'c' ),
		);
	}

	public function notification_dependency_with( Observer $observer ): Observer_Priority	{
		return Observer_Priority::NONE;
	}
}

class Comment_Syntax_Help_Item_Collection_Test extends WP_UnitTestCase {

	/**
	 * test all_items on empty collection.
	 * 
	 * @since 1.0.0
	 */
	public function test_empty_all_items() {
		$o = new Comment_Syntax_Help_Item_Collection();
		$ar = iterator_to_array( $o->all_items() );
		$this->assertTrue( empty( $ar ) );
	}

	public function test_constructor_same_ids() {

		$thrown = false;
		try {
			$o = new Comment_Syntax_Help_Item_Collection(
				new Comment_Syntax_Help_Item( 'a', 'b', 'c' ),
				new Comment_Syntax_Help_Item( 'b', 'b', 'c' ),
				new Comment_Syntax_Help_Item( 'a', 'ba', 'ca' ),
			);
		} catch ( Exception $e ) {
			$thrown = true;
		}
		$this->assertTrue( $thrown );
	}

	/**
	 * Test the add_items_at_top
	 *
	 * @since 1.0.0
	 */
	public function test_add_items_at_top() {

		// Adding after onstruction fnished throws.
		$thrown = false;
		try {
			$o = new Comment_Syntax_Help_Item_Collection();
			$o->add_items_at_top( new Comment_Syntax_Help_Item( 'a', 'b', 'c' ) );
		} catch ( Exception $e ) {
			$thrown = true;
		}
		$this->assertTrue( $thrown );

		// Add element on top with a mutator.
		$m = new Mock_Mutator_Add_Items_At_Top();
		Comment_Syntax_Help_Item_Collection::register_mutator( $m );
	
		$o = new Comment_Syntax_Help_Item_Collection();

		// Check order of elements generated by all_items and that there only 3.
		$ar = iterator_to_array( $o->all_items() );
		$this->assertSame( 3, count( $ar ) );
		$this->assertSame( 'a', $ar[0]->id );
		$this->assertSame( 'c', $ar[1]->id );
		$this->assertSame( 'b', $ar[2]->id );

		// test with some initial item
		$o = new Comment_Syntax_Help_Item_Collection(
			new Comment_Syntax_Help_Item( 'first', 'b', 'c' )
		);
		$ar = iterator_to_array( $o->all_items() );
		$this->assertSame( 4, count( $ar ) );
		$this->assertSame( 'a', $ar[0]->id );
		$this->assertSame( 'c', $ar[1]->id );
		$this->assertSame( 'b', $ar[2]->id );
		$this->assertSame( 'first', $ar[3]->id );

		Comment_Syntax_Help_Item_Collection::remove_observer( $m );


	}

	/**
	 * Test the add_items_at_bottom
	 *
	 * @since 1.0.0
	 */
	public function test_add_items_at_bottom() {

		// Adding after onstruction fnished throws.
		$thrown = false;
		try {
			$o = new Comment_Syntax_Help_Item_Collection();
			$o->add_items_at_bottom( new Comment_Syntax_Help_Item( 'a', 'b', 'c' ) );
		} catch ( Exception $e ) {
			$thrown = true;
		}
		$this->assertTrue( $thrown );

		// Add elements a mutator.
		$m = new Mock_Mutator_Add_Items_At_Bottom();
		Comment_Syntax_Help_Item_Collection::register_mutator( $m );
