declare(strict_types=1);

use calmpress\comments\Comment_Syntax_Help_Item_Collection;
use calmpress\comments\Comment_Syntax_Help_Item_Collection_Mutator;
use calmpress\comments\Comment_Syntax_Help_Item;
use calmpress\observer\Observer;
use calmpress\observer\Observer_Priority;

/**
 * A class to mock mutator that add items at the top
 */
class Mock_Mutator_Add_Items_At_Top implements Comment_Syntax_Help_Item_Collection_Mutator {
	public function mutate_by_ref( Comment_Syntax_Help_Item_Collection &$collection ): void {
		$collection->add_items_at_top(
			new Comment_Syntax_Help_Item( 'a', 'b', 'c' ),
			new Comment_Syntax_Help_Item( 'c', 'b', 'c' ),
			new Comment_Syntax_Help_Item( 'b', 'b', 'c' ),
		);
	}

	public function notification_dependency_with( Observer $observer ): Observer_Priority	{
		return Observer_Priority::NONE;
	}
}

/**
 * A class to mock mutator that add items at the bottom
 */
class Mock_Mutator_Add_Items_At_Bottom implements Comment_Syntax_Help_Item_Collection_Mutator {
	public function mutate_by_ref( Comment_Syntax_Help_Item_Collection &$collection ): void {
		$collection->add_items_at_top(
			new Comment_Syntax_Help_Item( 'a', 'b', 'c' ),
