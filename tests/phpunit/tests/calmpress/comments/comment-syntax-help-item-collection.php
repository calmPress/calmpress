	/**
	 * Test the item addition at API at mixed order
	 *
	 * @since 1.0.0
	 */
	public function test_add_items_mixed() {

		// Add elements a mutator.
		$m = new Mock_Mutator_Add_Mixed();
		Comment_Syntax_Help_Item_Collection::register_mutator( $m );
		$o = new Comment_Syntax_Help_Item_Collection();

		// Check order of elements generated by all_items and that there only 3.
		$ar = iterator_to_array( $o->all_items() );
		$this->assertSame( 4, count( $ar ) );
		$this->assertSame( 'aaa', $ar[0]->id );
		$this->assertSame( 'a', $ar[1]->id );
		$this->assertSame( 'aa', $ar[2]->id );
		$this->assertSame( 'aaaa', $ar[3]->id );

		// test with some initial item
		$o = new Comment_Syntax_Help_Item_Collection(
			new Comment_Syntax_Help_Item( 'first', 'b', 'c' )
		);
		$ar = iterator_to_array( $o->all_items() );
		$this->assertSame( 5, count( $ar ) );
		$this->assertSame( 'aaa', $ar[0]->id );
		$this->assertSame( 'a', $ar[1]->id );
		$this->assertSame( 'first', $ar[2]->id );
		$this->assertSame( 'aa', $ar[3]->id );
		$this->assertSame( 'aaaa', $ar[4]->id );

		Comment_Syntax_Help_Item_Collection::remove_observer( $m );
	}

	/**
	 * Test the remove_items
	 *
	 * @since 1.0.0
	 */
	public function test_remove_items() {

		// Adding after onstruction fnished throws.
		$thrown = false;
		try {
			$o = new Comment_Syntax_Help_Item_Collection();
			$o->remove_items( 'a' );
		} catch ( Exception $e ) {
			$thrown = true;
		}
		$this->assertTrue( $thrown );

		$m = new Mock_Mutator_Remove_Items();
		Comment_Syntax_Help_Item_Collection::register_mutator( $m );
		$o = new Comment_Syntax_Help_Item_Collection();

		// Check order of elements generated by all_items and that there only 3.
		$ar = iterator_to_array( $o->all_items() );
		$this->assertSame( 2, count( $ar ) );
		$this->assertSame( 'bb', $ar[0]->id );
		$this->assertSame( 'ba', $ar[1]->id );

		Comment_Syntax_Help_Item_Collection::remove_observer( $m );
	}

	/**
	 * Test id_exists
	 * 
	 * @since 1.0.0
	 */
	public function test_id_exists() {
		$m = new Mock_Mutator_Remove_Items();
		Comment_Syntax_Help_Item_Collection::register_mutator( $m );
		$o = new Comment_Syntax_Help_Item_Collection();

		// Check order of elements generated by all_items and that there only 3.
		$this->assertTrue( $o->id_exists( 'bb' ) );
		$this->assertFalse( $o->id_exists( 'not here' ) );
		$this->assertFalse( $o->id_exists( 'bc' ) );

		Comment_Syntax_Help_Item_Collection::remove_observer( $m );
	}
}